function readMigration(path) {
  return readFileSync(resolve(repoRoot, path), 'utf8').trim();
}

function bundle(title, migrations, preamble = '') {
  return [
    `-- ${title}`,
    '-- Generated by scripts/generate-staging-sql-editor-release.mjs.',
    '-- Run only against the intended staging Supabase database after backup/preflight.',
    preamble.trim(),
    ...migrations.flatMap((path) => [`\n-- BEGIN ${path}`, readMigration(path), `-- END ${path}`]),
    '',
  ].filter(Boolean).join('\n');
}

