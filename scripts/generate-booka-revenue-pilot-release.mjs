import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const scriptDirectory = dirname(scriptPath);
const repositoryRoot = resolve(scriptDirectory, '..');

const migrationPaths = [
  resolve(repositoryRoot, 'db/migrations/122_booka_revenue_requests.sql'),
  resolve(repositoryRoot, 'db/migrations/123_revenue_attribution_verification.sql'),
];

const verificationPaths = [
  resolve(repositoryRoot, 'scripts/sql/verify_booka_revenue_requests.sql'),
  resolve(repositoryRoot, 'scripts/sql/verify_revenue_attribution_verification.sql'),
];

export const outputPath = resolve(
  repositoryRoot,
  'db/releases/2026-08-30-booka-revenue-pilot.sql',
);

function relativePath(filePath) {
  return filePath.slice(repositoryRoot.length + 1);
}

function readSql(filePath) {
  return readFileSync(filePath, 'utf8').trim();
}

function stripTransactionWrapper(sql, filePath) {
  const lines = sql.split(/\r?\n/);
  const beginIndexes = [];
  const commitIndexes = [];

  lines.forEach((line, index) => {
    if (/^\s*begin;\s*$/i.test(line)) beginIndexes.push(index);
    if (/^\s*commit;\s*$/i.test(line)) commitIndexes.push(index);
  });

  if (beginIndexes.length !== 1 || commitIndexes.length !== 1) {
    throw new Error(
      `${relativePath(filePath)} must contain exactly one BEGIN; and one COMMIT; wrapper`,
    );
  }

  if (beginIndexes[0] >= commitIndexes[0]) {
    throw new Error(`${relativePath(filePath)} has an invalid transaction wrapper`);
  }

  return lines
    .filter((_, index) => index !== beginIndexes[0] && index !== commitIndexes[0])
    .join('\n')
    .trim();
}

function section(filePath, sql) {
  return `-- Source: ${relativePath(filePath)}\n${sql}`;
}

export function buildBookaRevenuePilotSql() {
  const prerequisiteGuard = `-- Fail before applying changes if the SIAS attribution foundation is absent.
do $$
begin
  if to_regclass('public.sias_outcome_attributions') is null then
    raise exception 'Required table public.sias_outcome_attributions is missing. Apply the SIAS baseline migrations before this Booka revenue pilot bundle.';
  end if;
end
$$;`;

  const migrations = migrationPaths.map((filePath) =>
    section(filePath, stripTransactionWrapper(readSql(filePath), filePath)),
  );
  const verifications = verificationPaths.map((filePath) =>
    section(filePath, readSql(filePath)),
  );

  return [
    '-- Booka revenue pilot database release',
    '-- Generated by scripts/generate-booka-revenue-pilot-release.mjs. Do not edit by hand.',
    '-- Paste this complete file into the Supabase SQL Editor and run it once.',
    'begin;',
    prerequisiteGuard,
    ...migrations,
    '-- Verification runs inside the transaction so any failure rolls back the release.',
    ...verifications,
    'commit;',
    '',
  ].join('\n\n');
}

export function writeBookaRevenuePilotRelease() {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, buildBookaRevenuePilotSql(), 'utf8');
  return outputPath;
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  console.log(writeBookaRevenuePilotRelease());
}
